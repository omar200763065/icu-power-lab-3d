# Voice selection: ar-SA-HamedNeural is one of the most natural, warm, and prestigious Arabic male documentary narrator voices
VOICE = "ar-SA-HamedNeural"

async def generate():
    out_dir = os.path.join(os.getcwd(), "public", "audio")
    os.makedirs(out_dir, exist_ok=True)
    
    print(f"Generating audio using voice: {VOICE}")
    for idx, step in enumerate(STEPS):
        filename = f"{step['id']}.mp3"
        filepath = os.path.join(out_dir, filename)
        print(f"Generating [{idx+1}/{len(STEPS)}] {filename}...")
        communicate = edge_tts.Communicate(step["text"], VOICE, rate="-4%", pitch="+0Hz")
        await communicate.save(filepath)
        size = os.path.getsize(filepath)
        print(f"  Done: {filename} ({size} bytes)")

if __name__ == "__main__":
    asyncio.run(generate())
